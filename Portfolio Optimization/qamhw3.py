def min_var_weights(cov):
    n = cov.shape[0]

    def obj(w):
        return w @ cov @ w

    cons = [{"type": "eq", "fun": lambda w: np.sum(w) - 1}]
    bounds = [(0, 1)] * n
    w0 = np.ones(n) / n

    res = minimize(obj, w0, bounds=bounds, constraints=cons)
    return res.x

def active_weights(mu, cov, gamma=5):
    n = len(mu)

    def obj(x):
        return -(x @ mu - 0.5 * gamma * (x @ cov @ x))

    cons = [{"type": "eq", "fun": lambda x: np.sum(x)}]
    bounds = [(-0.5, 0.5)] * n
    x0 = np.zeros(n)

    res = minimize(obj, x0, bounds=bounds, constraints=cons)
    return res.x

